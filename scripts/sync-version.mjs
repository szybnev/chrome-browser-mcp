#!/usr/bin/env node
/**
 * Single Source of Truth version synchronizer.
 *
 * Source: root `package.json` -> `"version"`
 *
 * Usage:
 *   node scripts/sync-version.mjs                 # Sync all manifests/packages/code from root package.json
 *   node scripts/sync-version.mjs --check         # Fail if any target file is out of sync with root package.json
 *   node scripts/sync-version.mjs 0.3.0           # Set root package.json version to 0.3.0 and sync all targets
 *   node scripts/sync-version.mjs patch|minor|major
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const rootDir = resolve(__dirname, '..');
const rootPkgPath = resolve(rootDir, 'package.json');

const JSON_TARGETS = [
  'packages/protocol/package.json',
  'packages/server/package.json',
  'packages/extension/package.json',
  'packages/extension/manifest.json',
  'packages/mcp-app/package.json',
  'plugins/antigravity/plugin.json',
  'plugins/codex/plugin.json',
  'plugins/codex/.codex-plugin/plugin.json',
  'plugins/openchamber/package.json',
  'plugins/opencode/package.json',
  'plugins/claude/.claude-plugin/plugin.json',
  'plugins/claude/mcpb/manifest.json',
];

const VERSION_TS_REL = 'packages/protocol/src/version.ts';

function bumpSemver(current, kind) {
  const m = current.match(/^(\d+)\.(\d+)\.(\d+)(.*)$/);
  if (!m) throw new Error(`Invalid semver in root package.json: "${current}"`);
  let major = Number(m[1]);
  let minor = Number(m[2]);
  let patch = Number(m[3]);
  if (kind === 'major') {
    major += 1;
    minor = 0;
    patch = 0;
  } else if (kind === 'minor') {
    minor += 1;
    patch = 0;
  } else if (kind === 'patch') {
    patch += 1;
  }
  return `${major}.${minor}.${patch}`;
}

function isValidSemver(v) {
  return /^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$/.test(v);
}

const args = process.argv.slice(2);
const checkOnly = args.includes('--check');
const versionArg = args.find((a) => !a.startsWith('-'));

const rootPkgRaw = readFileSync(rootPkgPath, 'utf8');
const rootPkg = JSON.parse(rootPkgRaw);
let targetVersion = String(rootPkg.version);

if (versionArg) {
  if (checkOnly) {
    console.error('[sync-version] Cannot combine --check with a new version argument.');
    process.exit(1);
  }
  if (versionArg === 'patch' || versionArg === 'minor' || versionArg === 'major') {
    targetVersion = bumpSemver(targetVersion, versionArg);
  } else if (isValidSemver(versionArg)) {
    targetVersion = versionArg;
  } else {
    console.error(`[sync-version] Invalid version "${versionArg}". Expected x.y.z or patch|minor|major.`);
    process.exit(1);
  }

  rootPkg.version = targetVersion;
  writeFileSync(rootPkgPath, `${JSON.stringify(rootPkg, null, 2)}\n`, 'utf8');
  console.log(`[sync-version] Updated root package.json -> ${targetVersion}`);
}

const drifted = [];
let updatedCount = 0;

for (const rel of JSON_TARGETS) {
  const abs = resolve(rootDir, rel);
  const json = JSON.parse(readFileSync(abs, 'utf8'));
  if (json.version !== targetVersion) {
    if (checkOnly) {
      drifted.push(`${rel} (found "${json.version}", expected "${targetVersion}")`);
    } else {
      json.version = targetVersion;
      writeFileSync(abs, `${JSON.stringify(json, null, 2)}\n`, 'utf8');
      updatedCount += 1;
    }
  }
}

const versionTsAbs = resolve(rootDir, VERSION_TS_REL);
const expectedVersionTs = `// Auto-generated by scripts/sync-version.mjs from root package.json — do not edit manually.\nexport const APP_VERSION = '${targetVersion}';\n`;
let currentVersionTs = '';
try {
  currentVersionTs = readFileSync(versionTsAbs, 'utf8');
} catch {
  currentVersionTs = '';
}

if (currentVersionTs !== expectedVersionTs) {
  if (checkOnly) {
    drifted.push(`${VERSION_TS_REL} (out of sync with "${targetVersion}")`);
  } else {
    writeFileSync(versionTsAbs, expectedVersionTs, 'utf8');
    updatedCount += 1;
  }
}

if (checkOnly) {
  if (drifted.length > 0) {
    console.error(`[sync-version] Version drift detected (root package.json = ${targetVersion}):`);
    for (const d of drifted) console.error(`  ✗ ${d}`);
    console.error('Run `pnpm version:sync` to synchronize all files from root package.json.');
    process.exit(1);
  }
  console.log(`[sync-version] OK — all targets match root package.json (${targetVersion}).`);
} else {
  console.log(
    `[sync-version] Synced version ${targetVersion} (${updatedCount} file(s) updated, ${JSON_TARGETS.length + 1} targets checked).`,
  );
}
