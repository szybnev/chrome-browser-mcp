export const I18N_CATALOG: Record<SupportedLocale, Record<I18nKey, string>> = {
  en: EN,
  ru: RU,
  'zh-CN': ZH_CN,
};

export function resolveLocale(pref: LocalePreference = 'auto', browserLang?: string): SupportedLocale {
  if (pref !== 'auto') return pref;
  const raw = (
    browserLang ||
    (typeof navigator !== 'undefined' ? navigator.language : 'en')
  ).toLowerCase();
  if (raw.startsWith('ru')) return 'ru';
  if (raw.startsWith('zh')) return 'zh-CN';
  return 'en';
}

export function translate(locale: SupportedLocale, key: I18nKey): string {
  return I18N_CATALOG[locale]?.[key] ?? EN[key];
}
