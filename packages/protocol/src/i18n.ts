export const I18N_CATALOG: Record<SupportedLocale, Record<I18nKey, string>> = {
  en: EN,
  ru: RU,
  'zh-CN': ZH_CN,
};

export function resolveLocale(pref?: string): SupportedLocale {
  if (pref === 'ru') return 'ru';
  if (pref === 'zh-CN') return 'zh-CN';
  return 'en';
}

export function translate(
  locale: SupportedLocale,
  key: I18nKey,
  vars?: Record<string, string | number>,
): string {
  let text: string = I18N_CATALOG[locale]?.[key] ?? EN[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

export function isMacPlatform(): boolean {
  if (typeof navigator === 'undefined') return false;
  const uaData = (navigator as Navigator & { userAgentData?: { platform?: string } }).userAgentData;
  const plat = (uaData?.platform || navigator.platform || navigator.userAgent || '').toLowerCase();
  return plat.includes('mac');
}

export function getPauseShortcut(): string {
  return isMacPlatform() ? 'Option+Shift+P (⌥⇧P)' : 'Alt+Shift+P';
}
